-- Busca textual: ILIKE '%termo%' usa os índices GIN de trigramas.
-- Índices de trigrama: só se a extensão existir (schema pode ser public ou extensions).
do $$
declare esquema text;
begin
  select n.nspname into esquema
  from pg_extension e
  join pg_namespace n on n.oid = e.extnamespace
  where e.extname = 'pg_trgm';

  if esquema is null then
    raise notice 'pg_trgm ausente: índices de trigrama não criados (busca continua a funcionar).';
    return;
  end if;

  execute format('create index if not exists idx_livros_titulo_trgm on livros using gin (titulo %I.gin_trgm_ops)', esquema);
  execute format('create index if not exists idx_livros_sinopse_trgm on livros using gin (sinopse %I.gin_trgm_ops)', esquema);
  execute format('create index if not exists idx_autores_nome_trgm on autores using gin (nome %I.gin_trgm_ops)', esquema);
  execute format('create index if not exists idx_cursos_titulo_trgm on cursos using gin (titulo %I.gin_trgm_ops)', esquema);
  execute format('create index if not exists idx_cursos_plataforma_trgm on cursos using gin (plataforma %I.gin_trgm_ops)', esquema);
end $$;

-- ── Views para a API (nomes já achatados) ───────────────────

create or replace view livros_api with (security_invoker = true) as
select
  l.id, l.titulo, l.subtitulo, l.isbn, l.ano_publicacao, l.idioma,
  l.sinopse, l.capa_url, l.paginas, l.licenca, l.leituras, l.criado_em,
  a.id as autor_id, a.nome as autor_nome,
  c.id as categoria_id, c.nome as categoria_nome,
  f.slug as fonte_slug, f.nome as fonte_nome, f.url_base as fonte_url
from livros l
left join autores a    on a.id = l.autor_id
left join categorias c on c.id = l.categoria_id
left join fontes f     on f.id = l.fonte_id;

create or replace view cursos_api with (security_invoker = true) as
select * from cursos;

create or replace view podcasts_api with (security_invoker = true) as
select
  s.id, s.titulo, s.slug, s.descricao, s.capa_url, s.spotify_url,
  s.categoria, s.idioma, s.ativo,
  count(e.id) as total_episodios,
  max(e.publicado_em) as ultimo_episodio
from podcasts_shows s
left join podcasts_episodios e on e.show_id = s.id
group by s.id;

-- ── Busca de livros (RPC) ───────────────────────────────────
-- Todos os filtros são resolvidos no Postgres, com os índices acima.
-- p_* nulos são ignorados; p_busca usa ILIKE com índices de trigramas.

create or replace function public.buscar_livros(
  p_busca     text    default null,
  p_categoria bigint  default null,
  p_autor     bigint  default null,
  p_idioma    text    default null,
  p_licenca   text    default null,
  p_fonte     text    default null,
  p_formato   text    default null,
  p_limit     integer default 24,
  p_offset    integer default 0
)
returns setof livros_api
language sql
stable
as $$
  select v.*
  from livros_api v
  where (p_categoria is null or v.categoria_id = p_categoria)
    and (p_autor     is null or v.autor_id     = p_autor)
    and (p_idioma    is null or v.idioma       = p_idioma)
    and (p_licenca   is null or v.licenca      = p_licenca)
    and (p_fonte     is null or v.fonte_slug ilike '%' || p_fonte || '%')
    and (p_formato   is null or exists (
          select 1 from links_livros lk
          where lk.livro_id = v.id and lk.formato = p_formato))
    and (p_busca is null or (
          v.titulo    ilike '%' || p_busca || '%' or
          v.sinopse   ilike '%' || p_busca || '%' or
          v.autor_nome ilike '%' || p_busca || '%'))
  order by v.leituras desc, v.titulo asc
  limit greatest(p_limit, 1)
  offset greatest(p_offset, 0);
$$;

create or replace function public.contar_livros(
  p_busca     text    default null,
  p_categoria bigint  default null,
  p_autor     bigint  default null,
  p_idioma    text    default null,
  p_licenca   text    default null,
  p_fonte     text    default null,
  p_formato   text    default null
)
returns bigint
language sql
stable
as $$
  select count(*)
  from livros_api v
  where (p_categoria is null or v.categoria_id = p_categoria)
    and (p_autor     is null or v.autor_id     = p_autor)
    and (p_idioma    is null or v.idioma       = p_idioma)
    and (p_licenca   is null or v.licenca      = p_licenca)
    and (p_fonte     is null or v.fonte_slug ilike '%' || p_fonte || '%')
    and (p_formato   is null or exists (
          select 1 from links_livros lk
          where lk.livro_id = v.id and lk.formato = p_formato))
    and (p_busca is null or (
          v.titulo    ilike '%' || p_busca || '%' or
          v.sinopse   ilike '%' || p_busca || '%' or
          v.autor_nome ilike '%' || p_busca || '%'));
$$;

revoke all on function public.buscar_livros(text,bigint,bigint,text,text,text,text,integer,integer) from public;
revoke all on function public.contar_livros(text,bigint,bigint,text,text,text,text) from public;
grant execute on function public.buscar_livros(text,bigint,bigint,text,text,text,text,integer,integer) to anon, authenticated, service_role;
