-- pg_trgm é OPCIONAL: se o role não puder criar a extensão, o schema
-- continua e a busca funciona sem índice (sequential scan em ~104k linhas).
do $$
declare esquema text;
begin
  begin
    create schema if not exists extensions;
  exception when others then
    raise notice 'Schema extensions indisponível: %', sqlerrm;
  end;

  begin
    execute 'create extension if not exists pg_trgm with schema extensions';
  exception when others then
    begin
      execute 'create extension if not exists pg_trgm';
    exception when others then
      raise notice 'pg_trgm indisponível (%); a busca usará sequential scan.', sqlerrm;
    end;
  end;

  select n.nspname into esquema
  from pg_extension e
  join pg_namespace n on n.oid = e.extnamespace
  where e.extname = 'pg_trgm';

  if esquema is not null then
    begin
      execute format('grant usage on schema %I to postgres, anon, authenticated, service_role', esquema);
    exception when others then
      raise notice 'Sem permissão de grant no schema %: %', esquema, sqlerrm;
    end;
    perform set_config('search_path', 'public, ' || quote_ident(esquema), false);
  end if;
end $$;

-- ── Tabelas ─────────────────────────────────────────────────

create table if not exists fontes (
  id         bigint generated by default as identity primary key,
  slug       text not null unique,
  nome       text not null,
  tipo       text not null check (tipo in ('api','opds','rss','csv','scraping','manual')),
  url_base   text,
  ativa      smallint not null default 1
);

create table if not exists categorias (
  id         bigint generated by default as identity primary key,
  nome       text not null unique,
  descricao  text,
  criado_em  timestamptz default now()
);

create table if not exists autores (
  id            bigint generated by default as identity primary key,
  nome          text not null,
  nacionalidade text,
  biografia     text,
  criado_em     timestamptz default now()
);

create table if not exists livros (
  id              bigint generated by default as identity primary key,
  titulo          text not null,
  subtitulo       text,
  isbn            text,
  ano_publicacao  integer,
  idioma          text default 'pt',
  sinopse         text,
  capa_url        text,
  paginas         integer,
  autor_id        bigint references autores(id) on delete set null,
  categoria_id    bigint references categorias(id) on delete set null,
  fonte_id        bigint references fontes(id) on delete set null,
  fonte_id_externo text,
  licenca         text not null check (licenca in ('dominio-publico','cc0','cc-by','cc-by-sa','cc-by-nc','outro')),
  leituras        integer not null default 0,
  conteudo_texto  text,
  criado_em       timestamptz default now(),
  unique (fonte_id, fonte_id_externo)
);

create table if not exists links_livros (
  id            bigint generated by default as identity primary key,
  livro_id      bigint not null references livros(id) on delete cascade,
  formato       text not null check (formato in ('epub','pdf','txt','html','audiobook')),
  url           text not null,
  tamanho_bytes bigint,
  link_externo  smallint not null default 1,
  unique (livro_id, formato)
);

create table if not exists cursos (
  id         bigint generated by default as identity primary key,
  titulo     text not null,
  tipo       text default 'curso',
  area       text not null,
  plataforma text not null,
  url        text not null,
  licenca    text default 'gratuito',
  nivel      text default 'Iniciante',
  descricao  text,
  criado_em  timestamptz default now()
);

create table if not exists import_jobs (
  id          bigint generated by default as identity primary key,
  fonte_id    bigint not null references fontes(id),
  query       text,
  status      text not null default 'pendente' check (status in ('pendente','em_curso','concluido','erro')),
  total       integer default 0,
  processados integer default 0,
  erro        text,
  criado_em   timestamptz default now()
);

create table if not exists podcasts_shows (
  id           bigint generated by default as identity primary key,
  titulo       text not null,
  slug         text not null unique,
  descricao    text,
  capa_url     text,
  spotify_url  text,
  spotify_uri  text,
  categoria    text default 'Educação & Literatura',
  idioma       text default 'pt',
  ativo        smallint not null default 1,
  criado_em    timestamptz default now()
