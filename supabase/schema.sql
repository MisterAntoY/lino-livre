-- ── Recalcular agregados (RPC) ──────────────────────────────

create or replace function public.recalcular_estatisticas()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  truncate table contadores;

  insert into contadores (dimensao, chave, rotulo, total)
    select 'idioma', idioma, idioma, count(*) from livros
    where idioma is not null group by idioma;

  insert into contadores (dimensao, chave, rotulo, total)
    select 'licenca', licenca, licenca, count(*) from livros
    where licenca is not null group by licenca;

  insert into contadores (dimensao, chave, rotulo, total)
    select 'categoria', c.id::text, c.nome, count(l.id)
    from categorias c left join livros l on l.categoria_id = c.id
    group by c.id, c.nome;

  insert into contadores (dimensao, chave, rotulo, total)
    select 'fonte', f.id::text, f.nome, count(l.id)
    from fontes f left join livros l on l.fonte_id = f.id
    where f.ativa = 1 group by f.id, f.nome;

  insert into contadores (dimensao, chave, rotulo, total)
    select 'formato', formato, formato, count(distinct livro_id)
    from links_livros group by formato;

  insert into contadores (dimensao, chave, rotulo, total)
    select 'curso_tipo', coalesce(tipo,'outro'), coalesce(tipo,'outro'), count(*)
    from cursos group by coalesce(tipo,'outro');

  -- Contagem por autor (mesma tabela agregada usada pela D1).
  truncate table autor_totais;
  insert into autor_totais (autor_id, total)
    select autor_id, count(*)::int from livros
    where autor_id is not null group by autor_id;

  truncate table estatisticas;
  insert into estatisticas (chave, valor) values
    ('total_livros',     (select count(*) from livros)),
    ('total_leituras',   (select coalesce(sum(leituras),0) from livros)),
    ('total_autores',    (select count(*) from autores)),
    ('total_categorias', (select count(*) from categorias)),
    ('total_cursos',     (select count(*) from cursos)),
    ('total_fontes',     (select count(*) from fontes where ativa = 1)),
    ('atualizado_em_epoch', extract(epoch from now())::bigint);

  -- Ajusta as sequências após importações com IDs explícitos.
  perform setval(pg_get_serial_sequence('fontes','id'),          greatest(coalesce((select max(id) from fontes),1),1));
  perform setval(pg_get_serial_sequence('categorias','id'),      greatest(coalesce((select max(id) from categorias),1),1));
  perform setval(pg_get_serial_sequence('autores','id'),         greatest(coalesce((select max(id) from autores),1),1));
  perform setval(pg_get_serial_sequence('livros','id'),          greatest(coalesce((select max(id) from livros),1),1));
  perform setval(pg_get_serial_sequence('links_livros','id'),    greatest(coalesce((select max(id) from links_livros),1),1));
  perform setval(pg_get_serial_sequence('cursos','id'),          greatest(coalesce((select max(id) from cursos),1),1));
  perform setval(pg_get_serial_sequence('podcasts_shows','id'),  greatest(coalesce((select max(id) from podcasts_shows),1),1));
  perform setval(pg_get_serial_sequence('podcasts_episodios','id'), greatest(coalesce((select max(id) from podcasts_episodios),1),1));
end;
$$;

revoke all on function public.recalcular_estatisticas() from public, anon, authenticated;
grant execute on function public.recalcular_estatisticas() to service_role;

